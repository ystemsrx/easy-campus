const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");

const root = path.resolve(__dirname, "../miniprogram");
const themeSource = fs.readFileSync(path.join(root, "data/timetable-theme.ts"), "utf8");
const compiled = ts.transpileModule(themeSource, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
}).outputText;
const theme = { exports: {} };
new Function("module", "exports", "require", compiled)(theme, theme.exports, () => ({}));

const petSource = fs.readFileSync(path.join(root, "store/pet.ts"), "utf8");
const colors = [...petSource.matchAll(/\{ id: "([a-z]+)", label: "[^"]+", value: "(#[0-9a-f]{6})" \}/g)]
  .map(([, id, value]) => ({ id, value }));
if (colors.length !== 9) throw new Error("Pet color palette changed; update timetable corners");

const tones = ["blue", "cyan", "purple", "green", "orange", "rose", "yellow", "mint"];
const assets = path.join(root, "features/assets/timetable");
function writeCorner(name, color, opacity = 1) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="13" height="13" viewBox="0 0 13 13" fill="none">\n  <path d="M1.5 13A11.5 11.5 0 0 1 13 1.5" stroke="${color}" stroke-opacity="${opacity}" stroke-width="3" stroke-dasharray="6 3" stroke-linecap="butt" />\n</svg>\n`;
  fs.writeFileSync(path.join(assets, name), svg);
  return `/features/assets/timetable/${name}`;
}

const white = writeCorner("course-corner-white-13.svg", "#ffffff");
const soft = writeCorner("course-corner-soft-13.svg", "#ffffff", 0.88);
const companion = Object.fromEntries(colors.map(({ id, value }) => {
  const palette = theme.exports.companionCoursePalette(value);
  return [id, Object.fromEntries(tones.map((tone, index) => [
    tone,
    writeCorner(`course-corner-${id}-${tone}-13.svg`, palette[index]),
  ]))];
}));

const lines = [
  "// Generated by scripts/generate-timetable-course-corners.js.",
  "export const TIMETABLE_CORNER_ASSETS = {",
  `  white: ${JSON.stringify(white)},`,
  `  soft: ${JSON.stringify(soft)},`,
  "  companion: {",
  ...Object.entries(companion).map(([id, assetsByTone]) =>
    `    ${id}: ${JSON.stringify(assetsByTone)},`),
  "  },",
  "} as const;",
  "",
];
fs.writeFileSync(path.join(root, "data/timetable-corner-assets.ts"), lines.join("\n"));
